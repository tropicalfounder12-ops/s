# ══════════════════════════════════════════════════════════════
#  Frame helpers
# ══════════════════════════════════════════════════════════════
def _copy(frame):
    return [row[:] for row in frame]


def first_row(frame):
    """Index of the first row that has an opaque pixel (SPRITE_SIZE if the frame is empty)."""
    return next((i for i, row in enumerate(frame) if any(row)), SPRITE_SIZE)


def last_row(frame):
    """Index of the last row that has an opaque pixel (-1 if the frame is empty)."""
    return max((i for i, row in enumerate(frame) if any(row)), default=-1)


def ground_align(frame):
    """Shift a frame down so its lowest opaque pixel sits on the bottom row.

    The hand-drawn frames leave 0-3 empty rows under their feet (and differ from one
    another), which made the sprite hover above the taskbar at a different height in
    every pose. Aligning every frame to the same ground line fixes that.
    """
    shift = SPRITE_SIZE - 1 - last_row(frame)
    if shift <= 0:
        return _copy(frame)
    blank = [[_] * SPRITE_SIZE for _unused in range(shift)]
    return blank + _copy(frame)[:SPRITE_SIZE - shift]


def blink_variant(base_a, blink_a, base_b):
    """Build the blink pose for another idle frame by copying the changed rows over."""
    out = _copy(base_b)
    for i, (a_row, b_row) in enumerate(zip(base_a, blink_a)):
        if a_row != b_row:
            out[i] = b_row[:]
    return out


def to_put_data(frame, palette):
    """Colour rows in the format tkinter.PhotoImage.put() expects: '{#rrggbb ...} {...}'."""
    return " ".join(
        "{" + " ".join(palette.get(v, TRANSP) for v in row) + "}" for row in frame
    )


def _character(name, palette, sit_a, sit_b, blink, type_l, type_r, sleep_a, sleep_b):
    frames = {
        "sit_a": sit_a,
        "sit_b": sit_b,
        "blink_a": blink,
        "blink_b": blink_variant(sit_a, blink, sit_b),
        "type_l": type_l,
        "type_r": type_r,
        "sleep_a": sleep_a,
        "sleep_b": sleep_b,
    }
    return {
        "name": name,
        "palette": palette,
        "frames": {key: ground_align(f) for key, f in frames.items()},
    }


